// 현재 버전의 릴리즈 노트를 앱 번들에 심는다 → 오프라인·Store 상관없이 '이 버전의 새로운 기능'을 볼 수 있게.
// 소스: 레포 루트 releasenotes/v<version>.md (한·영 병기). 버전은 frontend/package.json.
// 출력: frontend/src/data/releaseNotes.generated.ts (커밋됨, prebuild/predev 훅으로 항상 최신 유지).
//
// GitHub 릴리즈 body 를 그때그때 받아오던 '업데이트 알림' 경로와 별개다 — 이건 내가 지금 쓰는 버전의 노트.
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const ROOT = join(__dirname, '..', '..');            // frontend/scripts -> repo root
const OUT = join(__dirname, '..', 'src', 'data', 'releaseNotes.generated.ts');

const version = JSON.parse(readFileSync(join(__dirname, '..', 'package.json'), 'utf8')).version;
const notePath = join(ROOT, 'releasenotes', `v${version}.md`);

// 한·영 섹션 분리 — '## 한국어' ~ ('---' | '## English'), '## English' ~ 끝.
// 못 나누면(형식이 다르면) 전체 md 를 양쪽에 넣는 fail-soft.
function section(md, header, stops) {
  const start = md.indexOf(header);
  if (start < 0) return null;
  const body = md.slice(start + header.length);
  let end = body.length;
  for (const s of stops) {
    const i = body.indexOf(s);
    if (i >= 0 && i < end) end = i;
  }
  return body.slice(0, end).trim();
}

let payload = 'null';
if (existsSync(notePath)) {
  const md = readFileSync(notePath, 'utf8');
  const ko = section(md, '## 한국어', ['\n---', '\n## English']);
  const en = section(md, '## English', []);
  const both = ko && en ? { ko, en } : { ko: md.trim(), en: md.trim() };
  payload = `{\n  ko: ${JSON.stringify(both.ko)},\n  en: ${JSON.stringify(both.en)},\n}`;
} else {
  console.warn(`[gen-release-notes] ${notePath} 없음 — RELEASE_NOTES=null 로 생성(버튼 자동 숨김).`);
}

const out = `// AUTO-GENERATED by scripts/gen-release-notes.mjs — 직접 수정 금지.
// 소스: releasenotes/v${version}.md · 갱신: prebuild/predev 훅 또는 \`node scripts/gen-release-notes.mjs\`.
export const RELEASE_NOTES_VERSION = ${JSON.stringify(version)};
export const RELEASE_NOTES: { ko: string; en: string } | null = ${payload};
`;

writeFileSync(OUT, out, 'utf8');
console.log(`[gen-release-notes] v${version} -> src/data/releaseNotes.generated.ts (${payload === 'null' ? 'empty' : 'ok'})`);
